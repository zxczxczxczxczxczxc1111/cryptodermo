/**
 * Общее для обоих быстрых окон: маленького окна по глобальному сочетанию
 * (`QuickWindow.tsx`) и палитры Ctrl+K внутри приложения
 * (`QuickPalette.tsx`).
 *
 * Появился 19.08.2026 при удалении режима `--quick`: эти три символа жили в
 * `QuickAccess.tsx`, и оба оставшихся быстрых окна импортировали их оттуда,
 * то есть из экрана, который больше не существует.
 *
 * Второе исключение из правила «каждый модуль держит свою копию мелких
 * хелперов» (первое - `base64.ts`), заведено с явного согласия пользователя.
 * Правило в CLAUDE.md обновлено. Класть это в `quickBridge.ts` было нельзя:
 * тот сознательно не зависит от `totp.ts` (там своя копия проверки, чтобы не
 * тащить вычисление кодов в окно, которое их не считает), а `totpField`
 * живёт как раз на `looksLikeTotp`.
 */

import type { Item } from "./vaultStore";
import { looksLikeTotp } from "./totp";

/** Сколько результатов показывать. Больше семи в окне такой высоты не
 * помещается, а листать длинный список в режиме «быстро» никто не станет:
 * проще дописать буквы. */
export const MAX_RESULTS = 7;

/** Быстрый доступ бесполезен без PIN: разбор мастер-пароля занимает
 * несколько секунд, что противоречит самой идее быстрого окна. */
export const NO_PIN_MESSAGE =
  "Быстрый доступ работает только с настроенным PIN-кодом. Откройте приложение обычным способом и включите PIN в настройках.";

/** Поле с кодом двухфакторки, если оно у записи есть. */
export function totpField(item: Item) {
  return item.fields.find((f) => looksLikeTotp(f.value)) ?? null;
}
